// In-Memory Mock Database
class MockDb {
  constructor() {
    this.collections = new Map();
  }
  collection(name) {
    if (!this.collections.has(name)) this.collections.set(name, new Map());
    const store = this.collections.get(name);
    return {
      doc: (id) => ({
        id,
        get: async () => {
          const d = store.get(id);
          return { id, exists: !!d, data: () => (d ? { ...d } : undefined) };
        },
        set: async (val, opts = {}) => {
          if (opts.merge && store.has(id)) {
            store.set(id, { ...store.get(id), ...val });
          } else {
            store.set(id, { ...val });
          }
        },
        update: async (val) => {
          if (!store.has(id)) throw new Error(`Document ${id} does not exist`);
          store.set(id, { ...store.get(id), ...val });
        },
        delete: async () => store.delete(id)
      }),
      where: (field, op, value) => ({
        get: async () => {
          const results = [];
          for (const [id, item] of store.entries()) {
            if (op === '==' && item[field] === value) results.push({ id, data: () => ({ ...item }) });
          }
          return { docs: results };
        }
      })
    };
  }
}

